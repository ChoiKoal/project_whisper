    result={'tiles/grove_rock_field.png':rock_field()}
    for deep,stem in [(False,'t5a_water'),(True,'t5b_water2')]:
        atlas=Image.new('RGBA',(256,64))
        for phase in range(2): atlas.alpha_composite(water_frame(deep,phase),(phase*128,0))
        result[f'tiles/{stem}.png']=water_frame(deep,0)
        result[f'tiles/{stem}_anim.png']=atlas
    return result
